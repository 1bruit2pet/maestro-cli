T = TypeVar('T', bound=BaseModel)


@dataclass
class ValidationResult:
    """Result of validating a structured output"""
    status: OutputStatus
    output: Optional[BaseModel] = None
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    raw_input: Optional[str] = None
    repaired: bool = False
    
    def is_valid(self) -> bool:
        """Check if validation passed"""
        return self.status == OutputStatus.VALID or self.status == OutputStatus.REPAIRED


class StructuredOutputValidator:
    """
    Validates and parses LLM responses into structured outputs.
    Handles repair prompts when validation fails.
    """
    
    # Map output_type to Pydantic model class
    OUTPUT_MODELS: Dict[OutputType, Type[BaseModel]] = {
        OutputType.COMPOSE: ComposeOutput,
        OutputType.ARRANGE: ArrangeOutput,
        OutputType.ORCHESTRATE: OrchestrateOutput,
        OutputType.CRITIQUE: "Critique",  # Imported from models.critique
        OutputType.REPAIR: RepairOutput,
        OutputType.ANALYZE: AnalyzeOutput,
    }
    
    def __init__(
        self,
        repair_prompt_generator: Optional[Callable[[str, OutputType, List[str]], str]] = None,
        max_repair_attempts: int = 3
    ):
        self.repair_prompt_generator = repair_prompt_generator
        self.max_repair_attempts = max_repair_attempts
        
    def validate(
        self,
        raw_output: Union[str, Dict[str, Any]],
        output_type: OutputType
    ) -> ValidationResult:
        """
        Validate a raw LLM output against the expected schema.
        
        Args:
            raw_output: Raw output from LLM (JSON string or dict)
            output_type: Type of output expected
            
        Returns:
            ValidationResult with status and parsed output
        """
        # Parse string to dict if needed
        if isinstance(raw_output, str):
            raw_dict = self._safe_parse_json(raw_output)
        else:
            raw_dict = raw_output
            
        # Add output_type if missing
        if raw_dict and "output_type" not in raw_dict:
            raw_dict["output_type"] = output_type.value
        
        model_class = self.OUTPUT_MODELS.get(output_type)
        if model_class is None:
            return ValidationResult(
                status=OutputStatus.INVALID,
                errors=[f"Unknown output type: {output_type}"]
            )
        
        # Handle Critique special case (imported from models)
        if output_type == OutputType.CRITIQUE:
            from maestro_cli.models.critique import Critique
            model_class = Critique
        
        # Try to parse and validate
        try:
            output = model_class(**raw_dict)
            return ValidationResult(
                status=OutputStatus.VALID,
                output=output,
                raw_input=raw_output if isinstance(raw_output, str) else json.dumps(raw_output)
            )
        except ValidationError as e:
            errors = [f"{err['loc']}: {err['msg']}" for err in e.errors()]
            logger.warning(f"Validation failed for {output_type}: {errors}")
            
            # Attempt repair if possible
            if self.repair_prompt_generator and self.max_repair_attempts > 0:
                repaired_result = self._attempt_repair(
                    raw_output, output_type, errors, model_class
                )
                if repaired_result.is_valid():
                    return repaired_result
                return ValidationResult(
                    status=OutputStatus.INVALID,
                    errors=repaired_result.errors,
                    raw_input=raw_output if isinstance(raw_output, str) else json.dumps(raw_output)
                )
            
            return ValidationResult(
                status=OutputStatus.INVALID,
                errors=errors,
                raw_input=raw_output if isinstance(raw_output, str) else json.dumps(raw_output)
            )
        except Exception as e:
            logger.error(f"Unexpected error validating {output_type}: {e}")
            return ValidationResult(
                status=OutputStatus.INVALID,
                errors=[f"Unexpected error: {str(e)}"],
                raw_input=raw_output if isinstance(raw_output, str) else json.dumps(raw_output)
            )
    
    def validate_json_string(
        self,
        json_string: str,
        output_type: OutputType
    ) -> ValidationResult:
        """Validate a JSON string output"""
        return self.validate(json_string, output_type)
    
    def validate_dict(
        self,
        data: Dict[str, Any],
        output_type: OutputType
    ) -> ValidationResult:
        """Validate a dictionary output"""
        return self.validate(data, output_type)
    
    def _safe_parse_json(self, json_string: str) -> Dict[str, Any]:
        """Safely parse JSON, returning empty dict on failure"""
        try:
            return json.loads(json_string)
        except json.JSONDecodeError as e:
            logger.warning(f"Invalid JSON: {e}")
            return {}
    
    def _attempt_repair(
        self,
        raw_output: Union[str, Dict[str, Any]],
        output_type: OutputType,
        errors: List[str],
        model_class: Type[BaseModel]
    ) -> ValidationResult:
        """Attempt to repair a failed validation"""
        # Try to import call_llm if available, otherwise skip repair
        try:
            from maestro_cli.llm import call_llm
            llm_available = True
        except (ImportError, ModuleNotFoundError):
            llm_available = False
        
        for attempt in range(self.max_repair_attempts):
            repair_prompt = self.repair_prompt_generator(
                raw_output if isinstance(raw_output, str) else json.dumps(raw_output),
                output_type,
                errors
            )
            
            logger.info(f"Repair attempt {attempt + 1}/{self.max_repair_attempts} for {output_type}")
            
            try:
                # Call LLM for repair if available
                if llm_available:
                    repaired_json = call_llm(repair_prompt)
                else:
                    # No LLM available, cannot repair
                    logger.warning("LLM module not available, skipping repair")
                    break
                
                repaired_dict = self._safe_parse_json(repaired_json)
                
                output = model_class(**repaired_dict)
                return ValidationResult(
                    status=OutputStatus.REPAIRED,
                    output=output,
                    raw_input=raw_output if isinstance(raw_output, str) else json.dumps(raw_output),
                    repaired=True
                )
            except (ValidationError, Exception) as e:
                logger.debug(f"Repair attempt {attempt + 1} failed: {e}")
                if attempt == self.max_repair_attempts - 1:
                    break
                continue
        
        return ValidationResult(
            status=OutputStatus.INVALID,
            errors=[f"Failed to repair after {self.max_repair_attempts} attempts"] + errors,
            raw_input=raw_output if isinstance(raw_output, str) else json.dumps(raw_output)
        )


# ============================================================================
# DEFAULT VALIDATOR INSTANCE
# ============================================================================

def default_repair_prompt(
    raw_output: str,
    output_type: OutputType,
    errors: List[str]
) -> str:
    """Generate a repair prompt for the LLM"""
    error_list = "\n".join([f"- {e}" for e in errors])
    
    return f"""
You previously generated the following output for a {output_type.value} task:
{raw_output}

However, validation found the following issues:
{error_list}

Please fix these issues and return a corrected JSON output that strictly follows the schema.
Return ONLY the corrected JSON, no explanations or apologies.
"""


# Global validator instance
validator = StructuredOutputValidator(
    repair_prompt_generator=default_repair_prompt,
    max_repair_attempts=2
)


