class RepairOutput(BaseModel):
    """
    Structured output for the repair step.
    Contains fixes for issues detected during critique.
    """
    output_type: OutputType = OutputType.REPAIR
    project_id: str = Field(..., description="Unique project identifier")
    original_issues: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="List of issues that triggered the repair"
    )
    repairs_applied: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="List of repairs that were applied"
    )
    tracks_modified: List[str] = Field(
        default_factory=list,
        description="List of track names that were modified"
    )
    success: bool = Field(default=True, description="Were all repairs successful?")
    
    # Metadata
    model_used: str = Field(default="", description="LLM model used")
    tokens_used: int = Field(default=0, description="Tokens consumed")
    generated_at: str = Field(default="", description="ISO timestamp")
    
    class Config:
        json_schema_extra = {
            "example": {
                "output_type": "repair",
                "project_id": "my_song_001",
                "original_issues": [
                    {"type": "register_collision", "tracks": ["keys_main", "lead_main"]}
                ],
                "repairs_applied": [
                    {
                        "action": "raise_lead_register",
                        "target": "lead_main",
                        "params": {"octave_shift": +1}
                    }
                ],
                "tracks_modified": ["lead_main"],
                "success": True
            }
        }


